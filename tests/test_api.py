def test_index_route_ghosts_stale_received_rows(client):
    application_id = _created_id(_create(client))
    # Backdate this row past the inactivity window, directly.
    with open_session() as session:
        row = repo.get_application(session, application_id)
        stale = datetime.combine(
            utc_now().date()
            - timedelta(days=config.GHOST_AFTER_DAYS + 1),
            dt_time.min,
        )
        row.updated_at = stale
        session.commit()

    page = client.get("/")  # loading the dashboard runs the sweep
    assert page.status_code == 200

    with open_session() as session:
        row = repo.get_application(session, application_id)
    assert row.status == "ghosted"
    events = _events_with_times(application_id)
    pairs = [(e.from_status, e.to_status) for e in events]
    assert ("received", "ghosted") in pairs
    ghost_event = next(e for e in events if e.to_status == "ghosted")
    # the sweep stamps now, not the stale day
    assert ghost_event.changed_at > stale


