"""HTTP/API-level tests for the application routes and PDF uploads (PLAN.md §5).

Everything runs offline through FastAPI's TestClient against a throwaway
database under pytest's ``tmp_path``; uploaded "PDFs" are generated byte
strings, never real files. The live DATA_DIR is never touched (§7).
"""

from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from app import config, db, repo, uploads
from app.db import open_session
from app.main import create_app


@pytest.fixture()
def client(tmp_path, monkeypatch):
    """An app wired to a fresh temp DATA_DIR (database + upload files)."""
    data_dir = tmp_path / "data"
    # config reads it at call time for uploads; db binds its own copy and the
    # lazily-created engine/session factory must be dropped so lifespan's
    # init_db() rebuilds them against this test's temp dir.
    monkeypatch.setattr(config, "DATA_DIR", str(data_dir))
    monkeypatch.setattr(db, "DATA_DIR", str(data_dir))
    monkeypatch.setattr(db, "_default_engine", None)
    monkeypatch.setattr(db, "_default_factory", None)

    with TestClient(create_app()) as test_client:
        yield test_client

    # Don't let later tests (e.g. repo-level ones using their own engines) or
    # a re-imported module reuse this test's temp database.
    db._default_engine = None
    db._default_factory = None


@pytest.fixture()
def data_dir(tmp_path):
    """The on-disk root the client fixture pointed DATA_DIR at."""
    return tmp_path / "data"


