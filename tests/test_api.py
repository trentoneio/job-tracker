def test_create_redirects_to_detail_and_starts_received(client):
    response = _create(client)
    application_id = _created_id(response)
    assert response.headers["location"] == f"/applications/{application_id}"

    with open_session() as session:
        row = repo.get_application(session, application_id)
    assert row is not None and row.status == "received"
    # creation writes exactly one initial status event (§4)
    assert events_for(application_id) == [(None, "received")]

    page = client.get(f"/applications/{application_id}")
    assert page.status_code == 200
    for text in ("Acme Corp", "Backend Engineer", "received"):
        assert text in page.text


def test_index_placeholder_lists_applications(client):
    home = client.get("/")
    assert home.status_code == 200
    # S3 builds the real dashboard; this is only a placeholder (§5/§6)
    assert "No applications yet" in home.text

    _create(client, job_title="Platform Engineer")
    home = client.get("/")
    assert "Acme Corp" in home.text and "Platform Engineer" in home.text


def test_tampered_status_on_create_is_ignored(client):
    # The create form has no status field; a tampered one must not stick (§4).
    _create(client, **{"status": "offer"})

    with open_session() as session:
        rows = repo.list_applications(session)
    assert len(rows) == 1 and rows[0].status == "received"


def test_create_validation_errors_rerender_with_values_preserved(client):
    response = _create(client, company="", job_title="Test Engineer", applied_on="not-a-date")

    assert response.status_code == 200  # re-rendered form, not a redirect
    for message in ("Company is required.", "is not a valid date"):
        assert message in response.text
    # the user's input comes back on the form (§5 inline errors)
    assert 'value="Test Engineer"' in response.text

    with open_session() as session:
        assert repo.list_applications(session) == []  # nothing was persisted


def test_create_with_both_pdfs_stores_bytes_and_metadata(client, data_dir):
    resume = _pdf("my-cv.pdf", b"resume-bytes")
    application_pdf = _pdf("cover-letter.pdf", b"application-bytes")
    response = _create(
        client, files=[("resume_pdf", resume), ("application_pdf", application_pdf)]
    )
    application_id = _created_id(response)

    # exact bytes land under the stable per-application paths (§7)
    root = data_dir / "uploads" / str(application_id)
    assert (root / "resume.pdf").read_bytes() == resume[1]
    assert (root / "application.pdf").read_bytes() == application_pdf[1]

    with open_session() as session:
        row = repo.get_application(session, application_id)
    assert row.resume_file_name == "my-cv.pdf"
    assert row.application_file_name == "cover-letter.pdf"
    # the database keeps DATA_DIR-relative paths; original names stay metadata-only
    assert row.resume_pdf == f"uploads/{application_id}/resume.pdf"
    assert row.application_pdf == f"uploads/{application_id}/application.pdf"

    page = client.get(f"/applications/{application_id}")
    assert "my-cv.pdf" in page.text and "cover-letter.pdf" in page.text


