def test_upload_rejects_oversized_file_before_disk_write(client, data_dir):
    cap = uploads.max_upload_bytes()
    oversized = ("huge.pdf", b"%PDF-1.7\n" + b"\x00" * cap, "application/pdf")
    assert len(oversized[1]) > cap

    response = _create(client, files=[("resume_pdf", oversized)])

    assert response.status_code == 200
    assert "upload limit" in response.text
    with open_session() as session:
        assert repo.list_applications(session) == []
    # size is checked before any write — nothing may exist on disk at all
    assert not (data_dir / "uploads").exists()


def test_create_disk_failure_cleans_up_row_and_files(client, data_dir, monkeypatch):
    def exploding_store(**kwargs):
        raise OSError("disk full")

    monkeypatch.setattr(uploads, "store_upload", exploding_store)

    response = _create(client, files=[("resume_pdf", _pdf("cv.pdf", b"lost"))])

    assert response.status_code == 200
    assert "Could not save the uploaded file" in response.text
    with open_session() as session:
        assert repo.list_applications(session) == []  # half-created row rolled back
    uploads_root = data_dir / "uploads"
    assert not uploads_root.exists() or list(uploads_root.glob("*")) == []


