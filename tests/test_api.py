def test_update_status_appends_event_and_redirects(client):
    application_id = _created_id(_create(client))

    response = _update(client, application_id, status="interviewing")
    assert response.status_code == 303
    assert events_for(application_id) == [(None, "received"), ("received", "interviewing")]

    page = client.get(f"/applications/{application_id}")
    assert "interviewing" in page.text


def test_update_replaces_pdf_and_updates_metadata(client, data_dir):
    application_id = _created_id(
        _create(client, files=[("resume_pdf", _pdf("cv-v1.pdf", b"old-bytes"))])
    )

    response = _update(
        client,
        application_id,
        status="interviewing",
        files=[("resume_pdf", _pdf("cv-v2.pdf", b"new-bytes"))],
    )
    assert response.status_code == 303

    # the file was replaced in place at its stable path (§7)
    stored = data_dir / "uploads" / str(application_id) / "resume.pdf"
    assert stored.read_bytes() == b"%PDF-1.7\n% new-bytes\n%%EOF"

    with open_session() as session:
        row = repo.get_application(session, application_id)
    assert row.resume_file_name == "cv-v2.pdf"  # metadata follows the replacement

    download = client.get(f"/files/{application_id}/resume")
    assert download.status_code == 200
    assert download.content == b"%PDF-1.7\n% new-bytes\n%%EOF"
    assert 'filename="cv-v2.pdf"' in download.headers["content-disposition"]


def test_update_without_file_keeps_existing_pdf_and_events(client, data_dir):
    application_id = _created_id(
        _create(client, files=[("resume_pdf", _pdf("cv.pdf", b"kept-bytes"))])
    )

    response = _update(client, application_id, notes="only a note edit")
    assert response.status_code == 303

    stored = data_dir / "uploads" / str(application_id) / "resume.pdf"
    assert stored.read_bytes() == b"%PDF-1.7\n% kept-bytes\n%%EOF"
    with open_session() as session:
        row = repo.get_application(session, application_id)
    assert row.resume_file_name == "cv.pdf" and row.notes == "only a note edit"
    # no status change -> no new event (§4); the initial one is still all we have
    assert events_for(application_id) == [(None, "received")]


def test_update_inline_errors_preserve_values_and_commit_nothing(client):
    application_id = _created_id(_create(client))

    response = _update(
        client,
        application_id,
        company="Renamed Corp",  # valid field that must NOT stick on failure
        status="bogus-status",
    )

    assert response.status_code == 200
    assert "must be one of" in response.text
    # the submitted values are echoed back for a retry (§5)
    assert 'value="Renamed Corp"' in response.text
    with open_session() as session:
        row = repo.get_application(session, application_id)
    assert row.company == "Acme Corp"  # nothing was written on validation failure
    assert events_for(application_id) == [(None, "received")]


