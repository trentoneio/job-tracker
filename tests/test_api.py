def _events_with_times(application_id):
    """The full event history with timestamps, oldest first."""
    with open_session() as session:
        return list(repo.get_status_events(session, application_id))


def test_update_backdates_the_appended_event(client):
    application_id = _created_id(_create(client))

    response = _update(
        client,
        application_id,
        status="interviewing",
        status_changed_on="2026-07-01",
    )
    assert response.status_code == 303

    events = _events_with_times(application_id)
    assert len(events) == 2
    # The backdated event legitimately sorts ahead of the creation-time one.
    changed = next(e for e in events if e.to_status == "interviewing")
    assert (changed.from_status, changed.to_status) == ("received", "interviewing")
    # The given calendar day becomes midnight UTC on that date.
    assert changed.changed_at.date() == date(2026, 7, 1)
    assert changed.changed_at.time().isoformat() == "00:00:00"


def test_update_blank_status_date_stamps_today(client):
    application_id = _created_id(_create(client))

    response = _update(client, application_id, status="rejected")
    assert response.status_code == 303

    events = _events_with_times(application_id)
    changed = next(e for e in events if e.to_status == "rejected")
    assert changed.changed_at.date() == utc_now().date()


