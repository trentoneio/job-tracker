def test_download_serves_stored_pdf_with_original_name(client):
    application_id = _created_id(
        _create(client, files=[("resume_pdf", _pdf("final-cv.pdf", b"download-bytes"))])
    )

    response = client.get(f"/files/{application_id}/resume")
    assert response.status_code == 200
    assert response.headers["content-type"] == "application/pdf"
    # original upload name, not the stable storage path (§7)
    assert 'filename="final-cv.pdf"' in response.headers["content-disposition"]
    assert response.content == b"%PDF-1.7\n% download-bytes\n%%EOF"


def test_download_404_for_missing_file_kind_app_or_deleted_on_disk(client, data_dir):
    # an application with no uploads at all
    bare_id = _created_id(_create(client))
    assert client.get(f"/files/{bare_id}/resume").status_code == 404
    assert client.get(f"/files/{bare_id}/application").status_code == 404

    # unknown application id and unknown kind
    assert client.get("/files/999/resume").status_code == 404
    assert client.get(f"/files/{bare_id}/bogus").status_code == 404

    # file present in the database but missing on disk (e.g. manually deleted)
    uploaded_id = _created_id(_create(client, files=[("resume_pdf", _pdf("cv.pdf", b"x"))]))
    stored = data_dir / "uploads" / str(uploaded_id) / "resume.pdf"
    stored.unlink()
    assert client.get(f"/files/{uploaded_id}/resume").status_code == 404
