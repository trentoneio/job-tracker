def _pdf(name: str, tag: bytes) -> tuple[str, bytes, str]:
    """A generated PDF-shaped payload for multipart uploads (offline §7)."""
    return name, b"%PDF-1.7\n% " + tag + b"\n%%EOF", "application/pdf"


def _create(client, files=None, **fields):
    payload = {
        "company": "Acme Corp",
        "job_title": "Backend Engineer",
        "applied_on": "2026-10-01",
        **(dict(fields) if fields else {}),
    }
    return client.post(
        "/applications/new", data=payload, files=files or [], follow_redirects=False
    )


def _update(client, application_id, files=None, **fields):
    payload = {
        "company": "Acme Corp",
        "job_title": "Backend Engineer",
        "applied_on": "2026-10-01",
        "status": "received",
        **(dict(fields) if fields else {}),
    }
    return client.post(
        f"/applications/{application_id}/update",
        data=payload,
        files=files or [],
        follow_redirects=False,
    )


def _created_id(response) -> int:
    assert response.status_code == 303, response.text
    return int(response.headers["location"].rsplit("/", 1)[1])


def events_for(application_id):
    """The full status_event chain for one application, as (from, to) pairs."""
    with open_session() as session:
        return [(e.from_status, e.to_status) for e in repo.get_status_events(session, application_id)]


