def test_delete_removes_row_events_and_files(client, data_dir):
    application_id = _created_id(
        _create(
            client,
            files=[("resume_pdf", _pdf("cv.pdf", b"gone-soon")), ("application_pdf", _pdf("app.pdf", b"gone-too"))],
        )
    )
    _update(client, application_id, status="interviewing")  # two events now

    response = client.post(f"/applications/{application_id}/delete", follow_redirects=False)
    assert response.status_code == 303
    assert response.headers["location"] == "/"

    with open_session() as session:
        assert repo.get_application(session, application_id) is None
    assert events_for(application_id) == []
    # both stored PDFs and their directory are gone (§7)
    assert not (data_dir / "uploads" / str(application_id)).exists()


def test_unknown_application_ids_404(client):
    assert client.get("/applications/999").status_code == 404
    assert _update(client, 999).status_code == 404
    assert client.post("/applications/999/delete", follow_redirects=False).status_code == 404


