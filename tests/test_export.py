def test_events_full_history_matches_repo_order_with_company_join(client):
    _seed(client)
    response = client.get("/api/events.csv")
    _assert_download_filename(response, "status_events")

    rows = _parse_csv(response.text)
    assert rows[0] == EVENT_COLUMNS

    with open_session() as session:
        events = repo.get_status_events_for_filter(session)
        companies = {app.id: app.company for app in repo.list_applications(session)}
    # One row per event — initial creation included (empty from_status) — in
    # exactly the repository's deterministic order, company names joined.
    assert rows[1:] == [_event_row(event, companies[event.application_id]) for event in events]

    # 4 applications, two of them changed once: 6 events total; each app's
    # first row is its creation with an empty from_status.
    assert len(events) == 6
    by_app: dict[str, list[list[str]]] = {}
    for row in rows[1:]:
        by_app.setdefault(row[0], []).append(row)
    for app_id, app_rows in by_app.items():
        assert app_rows[0][2] == "" and app_rows[0][3] == "received"


def test_events_company_filter_matches_same_predicate(client):
    _seed(client)
    response = client.get("/api/events.csv", params={"company": "Acme Corp"})

    rows = _parse_csv(response.text)
    with open_session() as session:
        events = repo.get_status_events_for_filter(session, company="Acme Corp")
        companies = {
            app.id: app.company
            for app in repo.list_applications(session, company="Acme Corp")
        }
    assert rows[1:] == [_event_row(event, companies[event.application_id]) for event in events]
    # A2's full two-event history plus A1's single creation — Globex absent.
    assert [row[1] for row in rows[1:]] == ["Acme Corp"] * 3


