"""CSV export endpoint tests (PLAN.md §5, S5).

Everything runs offline through FastAPI's TestClient against a throwaway
database under pytest's ``tmp_path``; uploaded "PDFs" are generated byte
strings. Expected rows are derived from the *same* repository functions the
endpoints use (no re-implemented filtering logic), so these tests prove the
exports match the dashboard slice and the database exactly. The live
DATA_DIR is never touched (§7).
"""

