def _pdf(name: str, tag: bytes) -> tuple[str, bytes, str]:
    """A generated PDF-shaped payload for multipart uploads (offline §7)."""
    return name, b"%PDF-1.7\n% " + tag + b"\n%%EOF", "application/pdf"


def _seed(client):
    """Four applications across two companies/dates with a known event history.

    Returns ``R`` — the UTC "today" all applied dates are offset from:

    * A1 Acme Corp / Backend Engineer, R-10, received, both PDFs (distinct
      original filenames, notes containing CSV-hostile characters).
    * A2 Acme Corp / SRE, R-30, then changed to rejected. No PDFs.
    * B1 Globex / Data Analyst, R-4, then changed to offer. Application PDF only.
    * C1 Initech / Frontend Dev, R-2, still received. No PDFs.
    """
    R = utc_now().date()

    def at(days_ago: int) -> str:
        return (R - timedelta(days=days_ago)).isoformat()

    a1 = client.post("/applications/new", data={
        "company": "Acme Corp",
        "job_title": "Backend Engineer",
        "applied_on": at(10),
        "reference_number": "REF-A",
        "job_posting_url": "https://example.com/a",
        "notes": 'Has, comma and "quotes"',
    }, files={
        "resume_pdf": _pdf("my-resume-final.pdf", b"RESUME"),
        "application_pdf": _pdf("app-copy (2).pdf", b"APP"),
    }, follow_redirects=False)
    a1_id = int(a1.headers["location"].rsplit("/", 1)[1])

    a2 = client.post("/applications/new", data={
        "company": "Acme Corp",
        "job_title": "SRE",
        "applied_on": at(30),
        "reference_number": "REF-D",
    }, follow_redirects=False)
    a2_id = int(a2.headers["location"].rsplit("/", 1)[1])

    b1 = client.post("/applications/new", data={
        "company": "Globex",
        "job_title": "Data Analyst",
        "applied_on": at(4),
    }, files={"application_pdf": _pdf("cover-letter.pdf", b"COVER")},
        follow_redirects=False)
    b1_id = int(b1.headers["location"].rsplit("/", 1)[1])

    client.post("/applications/new", data={
        "company": "Initech",
        "job_title": "Frontend Dev",
        "applied_on": at(2),
        "reference_number": "REF-C",
    }, follow_redirects=False)

    # Status changes (each appends exactly one event row): A2 -> rejected,
    # B1 -> offer. Fields echo the created values so only status moves.
    client.post(f"/applications/{a2_id}/update", data={
        "company": "Acme Corp",
        "job_title": "SRE",
        "applied_on": at(30),
        "reference_number": "REF-D",
        "status": "rejected",
    }, follow_redirects=False)
    client.post(f"/applications/{b1_id}/update", data={
        "company": "Globex",
        "job_title": "Data Analyst",
        "applied_on": at(4),
        "status": "offer",
    }, follow_redirects=False)

    return R


def _parse_csv(text: str) -> list[list[str]]:
    """All CSV rows (header first) as lists of strings."""
    return [row for row in csv.reader(io.StringIO(text))]


def _app_row(app) -> list[str]:
    """One application serialized exactly the way the endpoint must (§5)."""
    return [
        str(app.id),
        app.company,
        app.job_title,
        app.reference_number or "",
        app.applied_on.isoformat(),
        app.status,
        app.job_posting_url or "",
        app.notes or "",
        app.resume_file_name or "",  # original filename as stored in S2
        app.application_file_name or "",  # original filename as stored in S2
        app.created_at.isoformat(),
        app.updated_at.isoformat(),
    ]


def _event_row(event, company: str) -> list[str]:
    """One status event serialized exactly the way the endpoint must (§5)."""
    return [
        str(event.application_id),
        company,
        event.from_status or "",  # initial creation has no previous status
        event.to_status,
        event.changed_at.isoformat(),
    ]


def _assert_download_filename(response, prefix: str) -> None:
    assert response.status_code == 200
    assert "text/csv" in response.headers["content-type"]
    disposition = response.headers["content-disposition"]
    pattern = rf'^attachment; filename="{prefix}_\d{{8}}_\d{{4}}\.csv"$'
    assert re.match(pattern, disposition), disposition


