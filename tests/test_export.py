def test_full_export_columns_and_rows_match_db_exactly(client):
    _seed(client)
    response = client.get("/api/export.csv")
    _assert_download_filename(response, "applications")

    rows = _parse_csv(response.text)
    # Columns exactly per §5 — including the two original-filename columns.
    assert rows[0] == APP_COLUMNS

    with open_session() as session:
        apps = repo.list_applications(session)
    # Every row, in order, matches the database content exactly.
    assert len(rows) - 1 == len(apps) == 4
    assert rows[1:] == [_app_row(app) for app in apps]

    # Spot-checks on the tricky cells: CSV-hostile notes survive quoting and
    # the PDF columns carry the original filenames, not the storage paths.
    a1 = next(app for app in apps if app.resume_file_name)
    row = rows[1 + [app.id for app in apps].index(a1.id)]
    assert row[7] == 'Has, comma and "quotes"'
    assert row[8] == "my-resume-final.pdf"
    assert row[9] == "app-copy (2).pdf"


def test_single_company_filter_matches_same_predicate(client):
    _seed(client)
    response = client.get("/api/export.csv", params={"company": "Acme Corp"})

    rows = _parse_csv(response.text)
    with open_session() as session:
        expected = repo.list_applications(session, company="Acme Corp")
    assert rows[1:] == [_app_row(app) for app in expected]
    # A1 (R-10) sorts before A2 (R-30); Globex/Initech are absent.
    assert [row[1] for row in rows[1:]] == ["Acme Corp", "Acme Corp"]


def test_status_subset_filter_matches_same_predicate(client):
    _seed(client)
    response = client.get(
        "/api/export.csv", params={"status": ["received", "offer"]}
    )

    rows = _parse_csv(response.text)
    with open_session() as session:
        expected = repo.list_applications(session, statuses=["received", "offer"])
    assert rows[1:] == [_app_row(app) for app in expected]
    # Newest first: C1 (R-2, received), B1 (R-4, offer), A1 (R-10, still
    # received); the rejected application is gone.
    assert [row[5] for row in rows[1:]] == ["received", "offer", "received"]


def test_date_range_filter_matches_same_predicate(client):
    R = _seed(client)
    date_from = (R - timedelta(days=4)).isoformat()  # inclusive lower bound
    response = client.get("/api/export.csv", params={"date_from": date_from})

    rows = _parse_csv(response.text)
    with open_session() as session:
        expected = repo.list_applications(session, date_from=R - timedelta(days=4))
    assert rows[1:] == [_app_row(app) for app in expected]
    # C1 (R-2) sorts first; B1 sits exactly on the from-date boundary and is
    # included.
    assert [row[4] for row in rows[1:]] == [(R - timedelta(days=2)).isoformat(), date_from]


